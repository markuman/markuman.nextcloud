import hashlib
import time

from ansible.module_utils.basic import AnsibleModule
from ansible_collections.markuman.nextcloud.plugins.module_utils.nextcloud import NextcloudHandler
from ansible_collections.markuman.nextcloud.plugins.module_utils.nextcloud import parameter_specs
from ansible_collections.markuman.nextcloud.plugins.module_utils.nextcloud import PASSWORDS_ROOT_FOLDER

# fields that are sent on update, taken from the existing password if not changed
UPDATE_FIELDS = ('label', 'password', 'username', 'url', 'notes', 'customFields', 'folder', 'favorite', 'hidden', 'edited')


def sha1(value):
    return hashlib.sha1(value.encode()).hexdigest()


def main():
    module = AnsibleModule(
        supports_check_mode=True,
        argument_spec=parameter_specs(dict(
            name=dict(required=True, type='str'),
            state=dict(type='str', choices=['present', 'absent'], default='present'),
            password=dict(required=False, type='str', no_log=True),
            # setting no_log=False on update_password avoids a false positive warning about not setting no_log
            update_password=dict(type='str', choices=['always', 'on_create'], default='on_create', no_log=False),
            username=dict(required=False, type='str'),
            url=dict(required=False, type='str'),
            notes=dict(required=False, type='str'),
            favorite=dict(required=False, type='bool'),
            folder=dict(required=False, type='str')
        ))
    )
    module.params["details"] = True
    nc = NextcloudHandler(module.params, module.fail_json)

    name = module.params.get('name')
    password = module.params.get('password')
    state = module.params.get('state')
    folder = module.params.get('folder')

    existing = nc.get_password(name)
    if len(existing) > 1:
        module.fail_json(msg='More than one password with label {0} exists. Cannot continue'.format(name))

    if state == 'absent':
        if not existing:
            module.exit_json(changed=False, password={})
        retval = {}
        if not module.check_mode:
            retval = nc.delete_password({'id': existing[0].get('id')})
        module.exit_json(changed=True, password=retval)

    # resolve folder name to id, None means it must be created
    folder_id = None
    if folder:
        folder_id = nc.get_passwords_folder(folder)

    desired = {}
    for key in ('username', 'url', 'notes', 'favorite'):
        if module.params.get(key) is not None:
            desired[key] = module.params.get(key)

    if not existing:
        if module.check_mode:
            module.exit_json(changed=True, password={})

        if folder:
            desired['folder'] = folder_id or nc.create_passwords_folder(folder).get('id')
        desired['label'] = name
        desired['password'] = password or nc.fetch_generated_password()[0]
        desired['hash'] = sha1(desired['password'])
        module.exit_json(changed=True, password=nc.create_password(desired))

    current = existing[0]
    if password is not None and module.params.get('update_password') == 'always':
        desired['password'] = password

    changes = dict((k, v) for k, v in desired.items() if current.get(k) != v)
    if folder and (folder_id is None or current.get('folder', PASSWORDS_ROOT_FOLDER) != folder_id):
        changes['folder'] = folder_id

    if not changes:
        module.exit_json(changed=False, password=existing)

    if module.check_mode:
        module.exit_json(changed=True, password=existing)

    if folder and changes.get('folder') is None:
        changes['folder'] = nc.create_passwords_folder(folder).get('id')

    # the passwords app resets every field that is not sent, so send them all
    obj = dict((k, current.get(k)) for k in UPDATE_FIELDS if current.get(k) is not None)
    obj.update(changes)
    obj['id'] = current.get('id')
    obj['hash'] = sha1(obj['password'])
    if 'password' in changes:
        obj['edited'] = int(time.time())
    module.exit_json(changed=True, password=nc.update_password(obj))


if __name__ == '__main__':
    main()
